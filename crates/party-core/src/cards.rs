//! Power cards (rules v11): the pure parts, kept apart from the game state so
//! every rule can be tested without driving a round. The catalog, the two
//! first-in-first-out lines and the Golden pool, draw odds, the comeback
//! system, the tier ladder for clashes, the vote tally with card weights, and
//! settlement. `game.rs` owns phases, hands and actions and calls in here.
//!
//! Source of truth: design/power-cards-v1/power-card-review-v11.xlsx, turned
//! into content/cards.json by scripts/cards-from-sheet.py.
use crate::cast::{self, Award, Facts, Role};
use rand::seq::SliceRandom;
use rand::Rng;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet, VecDeque};
use std::sync::OnceLock;

/// Power cards need a full cast and a crowd: below this they pause.
pub const MIN_PLAYERS: usize = 6;
pub const PRICE: i32 = 3;
/// Paid draws per player per session; free Underdog draws don't count.
pub const PAID_DRAWS: u32 = 4;
pub const GOLDEN_BASE: u32 = 10;
/// Added to your Golden chance by every draw that wasn't Golden.
pub const GOLDEN_STEP: u32 = 2;
/// Added for every round you start in the lead: it tempts the leader to spend.
pub const GOLDEN_LEAD_STEP: u32 = 1;
pub const GOLDEN_CAP: u32 = 20;
pub const RARE_ODDS: u32 = 25;
pub const BOUNTY_CAP: i32 = 3;
/// Rounds 1 and 2 never have Underdogs: one perfect Imposter round would
/// otherwise make every wrong civilian an Underdog at once.
pub const UNDERDOG_FROM_ROUND: u32 = 3;

