#[derive(Deserialize)]
struct CatalogFile {
    cards: Vec<Card>,
}

pub fn catalog() -> &'static [Card] {
    static CATALOG: OnceLock<Vec<Card>> = OnceLock::new();
    CATALOG.get_or_init(|| {
        serde_json::from_str::<CatalogFile>(include_str!("../content/cards.json"))
            .expect("content/cards.json is generated by scripts/cards-from-sheet.py")
            .cards
    })
}

pub fn card(id: &str) -> Option<&'static Card> {
    catalog().iter().find(|c| c.id == id)
}

pub fn tier_of(id: &str) -> Tier {
    card(id).map(|c| c.tier).unwrap_or(Tier::Common)
}

/// Why this card can't be played by this player at all (role, lead or bet),
/// before any window or target check. `None` means it can.
pub fn cant_play(id: &str, role: Role, leader: bool, stake: u32) -> Option<&'static str> {
    let c = card(id)?;
    if c.kind == Kind::Passive {
        return Some("Passive cards go off on their own.");
    }
    if c.cant_play.contains(&role) {
        return Some("This card can’t do anything for your role.");
    }
    if c.leader_cant_play && leader {
        return Some("The leader can’t play this card.");
    }
    if c.needs_bet && stake == 0 {
        return Some("Place a bet to play this card.");
    }
    None
}

// ---------------------------------------------------------------- the deck

/// Common and Rare cards come from two lines, shuffled once per session: a draw
/// takes the front card and used cards join the back, so every card in a tier
/// shows up before any repeats. Golden cards are a unique pool.
#[derive(Clone, Debug, Default)]
pub struct Deck {
    pub common: VecDeque<String>,
    pub rare: VecDeque<String>,
    pub golden: Vec<String>,
}

impl Deck {
    pub fn new(rng: &mut impl Rng) -> Self {
        let mut line = |tier: Tier| {
            let mut ids: Vec<String> = catalog()
                .iter()
                .filter(|c| c.tier == tier)
                .map(|c| c.id.clone())
                .collect();
            ids.shuffle(rng);
            ids
        };
        Deck {
            common: line(Tier::Common).into(),
            rare: line(Tier::Rare).into(),
            golden: line(Tier::Golden),
        }
    }

    fn take(&mut self, tier: Tier, held: &[String], rng: &mut impl Rng) -> Option<String> {
        let fits = |id: &String| !held.contains(id);
        match tier {
            Tier::Golden => {
                let open: Vec<usize> = (0..self.golden.len()).filter(|&i| fits(&self.golden[i])).collect();
                let &i = open.choose(rng)?;
                Some(self.golden.swap_remove(i))
            }
            Tier::Common | Tier::Rare => {
                let line = if tier == Tier::Common { &mut self.common } else { &mut self.rare };
                // A card you already hold is skipped and keeps its place at the front.
                let i = line.iter().position(fits)?;
                line.remove(i)
            }
        }
    }

    /// Draws at a rolled tier. An empty Golden pool rolls over to Rare, and a
    /// line with nothing that fits your hand falls to the other line.
    pub fn draw(&mut self, rolled: Tier, held: &[String], rng: &mut impl Rng) -> Option<(String, Tier)> {
        let order: &[Tier] = match rolled {
            Tier::Golden => &[Tier::Golden, Tier::Rare, Tier::Common],
            Tier::Rare => &[Tier::Rare, Tier::Common],
            Tier::Common => &[Tier::Common, Tier::Rare],
        };
        order
            .iter()
            .find_map(|&tier| self.take(tier, held, rng).map(|id| (id, tier)))
    }

    /// A played, traded or cleared card goes to the back of its line. Golden
    /// cards stay out for the rest of the session.
    pub fn give_back(&mut self, id: &str) {
        match tier_of(id) {
            Tier::Common => self.common.push_back(id.into()),
            Tier::Rare => self.rare.push_back(id.into()),
            Tier::Golden => {}
        }
    }
}

// ---------------------------------------------------------------- odds

/// Rolls a draw's tier. A higher Golden chance comes out of the Common share.
pub fn roll_tier(golden_pct: u32, rng: &mut impl Rng) -> Tier {
    let r = rng.gen_range(0..100);
    if r < golden_pct {
        Tier::Golden
    } else if r < golden_pct + RARE_ODDS {
        Tier::Rare
    } else {
        Tier::Common
    }
}

/// Your Golden chance after a draw of this tier.
pub fn chance_after_draw(chance: u32, drew: Tier) -> u32 {
    if drew == Tier::Golden {
        GOLDEN_BASE
    } else {
        (chance + GOLDEN_STEP).min(GOLDEN_CAP)
    }
}

/// Your Golden chance after starting a round in the lead.
pub fn chance_after_lead(chance: u32) -> u32 {
    (chance + GOLDEN_LEAD_STEP).min(GOLDEN_CAP)
}

/// The fake tier a Bluff Card announces: the same odds as a real draw.
pub fn bluff_tier(rng: &mut impl Rng) -> Tier {
    roll_tier(GOLDEN_BASE, rng)
}

// ---------------------------------------------------------------- comeback

/// How far behind the leader an Underdog is: a third of the target, rounded up.
pub fn underdog_gap(target: i32) -> i32 {
    (target + 2) / 3
}

/// Everyone tied for the top score. Nobody leads while the top score is 0.
pub fn leaders(scores: &BTreeMap<String, i32>) -> BTreeSet<String> {
    let top = scores.values().copied().max().unwrap_or(0);
    if top <= 0 {
        return BTreeSet::new();
    }
    scores.iter().filter(|(_, &s)| s == top).map(|(id, _)| id.clone()).collect()
}

/// Every player at least the gap behind the leader at the start of the round,
/// from round 3. No cap: a cap would make players throw points to stay in it.
pub fn underdogs(scores: &BTreeMap<String, i32>, target: i32, round: u32) -> BTreeSet<String> {
    if round < UNDERDOG_FROM_ROUND {
        return BTreeSet::new();
    }
    let top = scores.values().copied().max().unwrap_or(0);
    let gap = underdog_gap(target);
    scores
        .iter()
        .filter(|(_, &s)| top - s >= gap)
        .map(|(id, _)| id.clone())
        .collect()
}

/// The Rising Bounty: +1, growing by 1 for every round the same leaders
/// survive (cap +3), back to +1 after it pays or when the lead changes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Bounty {
    pub leaders: BTreeSet<String>,
    pub value: i32,
}

impl Default for Bounty {
    fn default() -> Self {
        Bounty { leaders: BTreeSet::new(), value: 1 }
    }
}

impl Bounty {
    /// The Bounty on these leaders at the start of a round.
    pub fn current(&self, leaders: &BTreeSet<String>) -> i32 {
        if *leaders == self.leaders {
            self.value
        } else {
            1
        }
    }

    /// Settles a round: what each Underdog is paid, and the next Bounty.
    pub fn settle(&self, leaders: &BTreeSet<String>, leader_lost: bool, underdogs: bool) -> (i32, Bounty) {
        let value = self.current(leaders);
        let paid = if leader_lost && underdogs && !leaders.is_empty() { value } else { 0 };
        let next = if paid > 0 {
            1
        } else if !leader_lost {
            (value + 1).min(BOUNTY_CAP)
        } else {
            value
        };
        (paid, Bounty { leaders: leaders.clone(), value: next })
    }
}

// ---------------------------------------------------------------- the tier ladder

/// A clash verdict. Every one is shown on every phone as a stamp.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Verdict {
    /// Lawyer Up stopped a card aimed at its owner.
    Blocked,
    /// Objection! cancelled a Common card (a Bluff Card included).
    Sustained,
    /// The card was too strong: Objection! against a Rare or Golden, or
    /// Pocket Veto against a Golden Ballot.
    Overruled,
    /// Pocket Veto took a vote out of the count.
    Vetoed,
    /// A Golden card went straight through Lawyer Up.
    Pierced,
}

/// The ladder: a higher tier wins; between equal tiers, the earlier play wins.
pub fn beats(a: (Tier, u32), b: (Tier, u32)) -> bool {
    a.0 > b.0 || (a.0 == b.0 && a.1 < b.1)
}

/// Cards that name a player, and so can run into that player's Lawyer Up.
pub fn aims_at_player(id: &str) -> bool {
    card(id).is_some_and(|c| c.target != Target::None)
}

/// A card (tier, seq) aimed at someone who played Lawyer Up (seq).
/// `None`: no clash, the card works (it came first, same tier).
pub fn against_lawyer(card: (Tier, u32), lawyer_seq: u32) -> Option<Verdict> {
    if beats((Tier::Rare, lawyer_seq), card) {
        Some(Verdict::Blocked)
    } else if card.0 == Tier::Golden {
        Some(Verdict::Pierced)
    } else {
        None
    }
}

/// Objection! against a card whose real tier is `objected`. A Bluff Card is a
/// Common whatever tier it announced, so it is always sustained.
pub fn objection(objected: Tier) -> Verdict {
    if objected == Tier::Common {
        Verdict::Sustained
    } else {
        Verdict::Overruled
    }
}

/// Pocket Veto against a vote, knowing whether that voter played Golden Ballot.
pub fn veto(golden_ballot: bool) -> Verdict {
    if golden_ballot {
        Verdict::Overruled
    } else {
        Verdict::Vetoed
    }
}

// ---------------------------------------------------------------- the vote

/// Who carries extra weight into the count.
#[derive(Clone, Debug, Default)]
pub struct Weights {
    pub judge: Option<String>,
    /// The Judge's ballot counts double at this party size.
    pub judge_doubles: bool,
    pub heavy: BTreeSet<String>,
    pub golden: BTreeSet<String>,
    pub vetoed: BTreeSet<String>,
}

impl Weights {
    /// A voter's counted weight. Golden Ballot is four in total, the Judge
    /// included, and can't be vetoed. The Imposter can't play it: their ballot
    /// names an accomplice pick, never a suspect. Otherwise the Imposter's vote
    /// never counts and a vetoed vote counts zero.
    pub fn of(&self, voter: &str, imposter: &str) -> u32 {
        if self.golden.contains(voter) {
            return 4;
        }
        if voter == imposter || self.vetoed.contains(voter) {
            return 0;
        }
        let judge = self.judge.as_deref() == Some(voter);
        let base = if judge && self.judge_doubles { 2 } else { 1 };
        base + u32::from(self.heavy.contains(voter))
    }
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Tally {
    /// Counted weight naming each player.
    pub against: BTreeMap<String, u32>,
    pub accused: Option<String>,
    pub judge_tiebreak: bool,
}

/// Counts the ballots with card weights. A tie lets the Imposter escape unless
/// the Judge, with a counted vote, named the Imposter among the tied leaders.
pub fn tally(votes: &BTreeMap<String, String>, imposter: &str, w: &Weights) -> Tally {
    let mut against: BTreeMap<String, u32> = BTreeMap::new();
    for (voter, target) in votes {
        let weight = w.of(voter, imposter);
        if weight > 0 {
            *against.entry(target.clone()).or_default() += weight;
        }
    }
    let max = against.values().copied().max().unwrap_or(0);
    let tied: Vec<&String> = against.iter().filter(|(_, &n)| n == max && n > 0).map(|(id, _)| id).collect();
    let judge_counted = w.judge.as_deref().is_some_and(|j| !w.vetoed.contains(j) && j != imposter);
    let tiebreak = tied.len() > 1
        && tied.iter().any(|id| *id == imposter)
        && judge_counted
        && w.judge.as_ref().and_then(|j| votes.get(j)).map(String::as_str) == Some(imposter);
    let accused = if tiebreak {
        Some(imposter.to_string())
    } else if tied.len() == 1 {
        Some(tied[0].clone())
    } else {
        None
    };
    Tally { against, accused, judge_tiebreak: tiebreak }
}

// ---------------------------------------------------------------- settlement

/// One active card played this round, as the host accepted it.
#[derive(Clone, Debug, Default)]
pub struct Play {
    pub seq: u32,
    pub owner: String,
    pub card: String,
    /// The player chosen: a target, a Sealed Alibi prediction, a Second
    /// Opinion backup, a Shadow's mark.
    pub pick: Option<String>,
    /// Blocked, sustained against, or otherwise stopped. It still used the
    /// owner's play for the round, so their passives still wait.
    pub cancelled: bool,
}

/// A player's seat in the round being settled.
#[derive(Clone, Debug, Default)]
pub struct Seat {
    pub role: Option<Role>,
    /// Score at the start of the round.
    pub before: i32,
    pub stake: u32,
    pub vote: Option<String>,
    /// Detective only: the accomplice pick was right.
    pub side_pick: bool,
    /// Passive cards held, oldest first.
    pub passives: Vec<String>,
    /// A Rain Check from last round: a lost bet costs nothing this round.
    pub rain_check: bool,
}

pub struct Round<'a> {
    pub seats: &'a BTreeMap<String, Seat>,
    /// The room's verdict, before any card changes it.
    pub facts: Facts,
    pub imposter: &'a str,
    pub accused: Option<&'a str>,
    pub tally: &'a Tally,
    pub plays: &'a [Play],
    /// The caught Imposter's Last Word, if it fired: whether they picked the real word.
    pub last_word: Option<bool>,
    pub underdogs: &'a BTreeSet<String>,
    pub leaders: &'a BTreeSet<String>,
    /// The Bounty on the leaders this round.
    pub bounty: &'a Bounty,
}

/// Points a card moved to a player, shown as a line in their breakdown.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Line {
    pub card: String,
    /// Who played or held the card (for Robin Hood and the Bounty, not you).
    pub from: String,
    pub points: i32,
}

#[derive(Clone, Debug, Default)]
pub struct Score {
    /// Role and bet, after card changes (Turncoat, Midas, Double or Nothing,
    /// the Underdog bonus, a Rain Check).
    pub award: Award,
    pub lines: Vec<Line>,
    /// Joins the Drink/Dare queue.
    pub lost: bool,
}

impl Score {
    pub fn cards(&self) -> i32 {
        self.lines.iter().map(|l| l.points).sum()
    }
    pub fn total(&self) -> i32 {
        self.award.total() + self.cards()
    }
}

#[derive(Clone, Debug, Default)]
pub struct Settled {
    pub scores: BTreeMap<String, Score>,
    /// Passive cards that went off: (owner, card). They leave the hand.
    pub fired: Vec<(String, String)>,
    /// Who carries a Rain Check into their next round.
    pub rain_checks: BTreeSet<String>,
    pub bounty_paid: i32,
    pub bounty_next: Bounty,
    pub leader_lost: bool,
}

const LAST_WORD: &str = "last-word";

fn villain(role: Option<Role>) -> bool {
    matches!(role, Some(Role::Imposter | Role::Accomplice))
}

/// Settles a round with cards, in the order of v11 Session rules 11:
/// the Last Word answer, then role scoring and bets (`cast::award`, with
/// card changes), card awards, passives, then the Bounty, Robin Hood,
/// Crown Heist and, last, Shadow, which copies its mark's final total.
pub fn settle(r: &Round) -> Settled {
    let active: BTreeMap<&str, &Play> = r.plays.iter().map(|p| (p.owner.as_str(), p)).collect();
    let live = |id: &str, card: &str| active.get(id).is_some_and(|p| !p.cancelled && p.card == card);
    let lw_right = r.last_word == Some(true);
    // A right Last Word: the Imposter's side scores as if the Imposter escaped.
    let villain_facts = if lw_right { Facts { escaped: true, ..r.facts } } else { r.facts };
    let turncoat = |id: &str| live(id, "turncoat");
    let escaped_for = |id: &str, role: Option<Role>| {
        if villain(role) || turncoat(id) { villain_facts.escaped } else { r.facts.escaped }
    };
    let mut out = Settled::default();

    // 1-3. Role scoring and bets, with the cards that change them.
    for (id, seat) in r.seats {
        let id = id.as_str();
        let facts = if villain(seat.role) || turncoat(id) { villain_facts } else { r.facts };
        let correct = seat.vote.as_deref() == Some(r.imposter);
        let saved = !correct
            && live(id, "second-opinion")
            && active[id].pick.as_deref() == Some(r.imposter);
        let mut award = match seat.role {
            _ if turncoat(id) => {
                let s = seat.stake as i32;
                Award {
                    base: if facts.escaped { 4 } else { 0 },
                    bet: if facts.escaped { s } else { -s },
                    lost: !facts.escaped,
                    ..Default::default()
                }
            }
            Some(role) => cast::award(role, &facts, correct || saved, seat.side_pick, seat.stake),
            None => Award::default(),
        };
        if saved {
            // The read counts as right; the bet still settles on the real vote.
            if let Some(role) = seat.role {
                award.bet = cast::award(role, &facts, false, seat.side_pick, seat.stake).bet;
            }
        }
        if live(id, "double-or-nothing") {
            award.bet *= 2;
        }
        let underdog = r.underdogs.contains(id);
        if underdog && award.bet > 0 {
            award.bet += 1;
        }
        if seat.rain_check && award.bet < 0 {
            award.bet = 0;
        }
        if live(id, "midas-touch") {
            for v in [&mut award.base, &mut award.bluff, &mut award.bonus, &mut award.bet] {
                if *v > 0 {
                    *v *= 3;
                }
            }
        }
        // An Underdog who loses a bet their points couldn't cover drinks.
        let uncovered = underdog && award.bet < 0 && -award.bet > seat.before;
        let lost = award.lost || uncovered;
        let mut score = Score { award, lines: vec![], lost };
        if live(id, "golden-pardon") && score.lost {
            score.lost = false;
            score.lines.push(Line { card: "golden-pardon".into(), from: id.into(), points: 5 });
        }
        out.scores.insert(id.into(), score);
    }

    // 4. Card awards (they survive a spotted player's void).
    let add = |out: &mut Settled, to: &str, card: &str, from: &str, points: i32| {
        if let Some(s) = out.scores.get_mut(to) {
            s.lines.push(Line { card: card.into(), from: from.into(), points });
        }
    };
    for p in r.plays.iter().filter(|p| !p.cancelled) {
        let Some(seat) = r.seats.get(&p.owner) else { continue };
        let owner = p.owner.as_str();
        match p.card.as_str() {
            "on-the-record" if seat.vote.as_deref() == Some(r.imposter) => add(&mut out, owner, "on-the-record", owner, 2),
            "sealed-alibi" => {
                let side_won = if villain(seat.role) || turncoat(owner) {
                    escaped_for(owner, seat.role)
                } else {
                    !r.facts.escaped
                };
                if side_won && p.pick.is_some() && p.pick.as_deref() == r.accused {
                    add(&mut out, owner, "sealed-alibi", owner, 3);
                }
            }
            "decoy-contract" if r.accused == Some(owner) => add(&mut out, owner, "decoy-contract", owner, 3),
            _ => {}
        }
    }

    // 5. Passives: the oldest one that can work goes off, only for players
    // who played no active card. A Last Word that fired takes the round.
    for (id, seat) in r.seats {
        if active.contains_key(id.as_str()) {
            continue;
        }
        if id == r.imposter && r.last_word.is_some() && seat.passives.iter().any(|c| c == LAST_WORD) {
            out.fired.push((id.clone(), LAST_WORD.into()));
            continue;
        }
        let correct = seat.vote.as_deref() == Some(r.imposter);
        let unvoted = r.tally.against.get(id).copied().unwrap_or(0) == 0;
        let score = &out.scores[id];
        let fired = seat.passives.iter().find(|c| match c.as_str() {
            "safety-net" => score.award.bet < 0 && seat.stake >= 2,
            "rain-check" => score.total() <= 0,
            "clean-hands" => correct && unvoted,
            "jackpot" => !score.lost,
            _ => false,
        });
        if let Some(card) = fired {
            let points = match card.as_str() {
                "safety-net" => 1,
                "clean-hands" => 2,
                "jackpot" => 4,
                _ => 0,
            };
            if points != 0 {
                add(&mut out, id, card, id, points);
            }
            if card == "rain-check" {
                out.rain_checks.insert(id.clone());
            }
            out.fired.push((id.clone(), card.clone()));
        }
    }

    // 6. The Bounty, Robin Hood and Crown Heist.
    out.leader_lost = r.leaders.iter().any(|id| out.scores.get(id).is_some_and(|s| s.lost));
    let (paid, next) = r.bounty.settle(r.leaders, out.leader_lost, !r.underdogs.is_empty());
    out.bounty_paid = paid;
    out.bounty_next = next;
    if paid > 0 {
        for u in r.underdogs {
            add(&mut out, u, "bounty", "", paid);
        }
    }
    let top_start = r.seats.values().map(|s| s.before).max().unwrap_or(0);
    for p in r.plays.iter().filter(|p| !p.cancelled) {
        let owner = p.owner.as_str();
        match p.card.as_str() {
            "robin-hood" => {
                for l in r.leaders {
                    add(&mut out, l, "robin-hood", owner, -5);
                }
                if r.underdogs.is_empty() {
                    add(&mut out, owner, "robin-hood", owner, 5);
                } else {
                    for u in r.underdogs {
                        add(&mut out, u, "robin-hood", owner, 2);
                    }
                }
            }
            "crown-heist" => {
                let Some(score) = out.scores.get(owner) else { continue };
                if !score.lost {
                    let now = r.seats[owner].before + score.total();
                    let gain = (top_start - now).max(0);
                    if gain > 0 {
                        add(&mut out, owner, "crown-heist", owner, gain);
                    }
                }
            }
            _ => {}
        }
    }

    // 7. Shadow, last: it copies its mark's final positive total.
    for p in r.plays.iter().filter(|p| !p.cancelled && p.card == "shadow") {
        let Some(mark) = p.pick.as_deref() else { continue };
        if mark == p.owner {
            continue;
        }
        let copied = out.scores.get(mark).map(Score::total).unwrap_or(0);
        if copied > 0 {
            add(&mut out, &p.owner.clone(), "shadow", mark, copied);
        }
    }
    out
}

/// Cardboard Crown at the end of a session: tied leaders holding the Crown
/// win alone (two Crown holders still share). Returns the final winners.
pub fn crown(winners: &[String], holders: &BTreeSet<String>) -> Vec<String> {
    let crowned: Vec<String> = winners.iter().filter(|w| holders.contains(*w)).cloned().collect();
    if winners.len() > 1 && !crowned.is_empty() {
        crowned
    } else {
        winners.to_vec()
    }
}

